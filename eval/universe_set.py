"""A test set for the Copilot beyond the parsed filings: lookups about companies that are only in the sections
index, e.g. "What was Hilton's total revenue in its latest fiscal year?".

The answers come from the warehouse's XBRL facts, which is also where the Copilot's facts source reads them, so
this set does not test the data. It tests what stands between a question and the data once ~1,600 companies are
indexed: finding the company by the name people use, picking the fiscal year (half the questions give none),
choosing the line item and getting the units right. Graded by numeric match; no LLM judge.

    uv run python -m eval.universe_set          # writes eval/universe_set.yaml
    FINSIGHT_QDRANT_URL=http://localhost:6333 uv run python -m eval.run --runs G --sets universe --universe
"""

from __future__ import annotations

import calendar
import logging
import random
from datetime import date, timedelta
from pathlib import Path

import duckdb
import yaml

from ingest import sections
from ingest.manifest import load_companies
from warehouse import db
from warehouse.fundamentals import Snapshot

log = logging.getLogger(__name__)
N = 40

# warehouse item -> how a question names it
ITEMS = {
    "revenue": "total revenue",
    "operating_income": "operating income",
    "net_income": "net income attributable to shareholders",
    "assets": "total assets",
    "current_liabilities": "total current liabilities",
    "cfo": "net cash from operating activities",
    "capex": "capital expenditure",
    "cash": "cash and cash equivalents",
}


def build(n: int = N) -> list[dict]:
    con = duckdb.connect(str(db.default_path()), read_only=True)
    filed = set(load_companies())
    rng = random.Random(11)
    pool = [f for t, f in sorted(sections.indexed().items()) if t not in filed]
    rng.shuffle(pool)
    out: list[dict] = []
    for f in pool:
        if len(out) == n:
            break
        snap = Snapshot(con, f["cik"], date.fromisoformat(f["filed"]) + timedelta(days=1))
        item = rng.choice(list(ITEMS))
        [value] = snap.annual(item, 1) or [None]
        if value is None or abs(value.value) < 1e6:
            continue
        month = calendar.month_name[f["fye_month"]]
        # the year the fiscal year nominally ends in: one that closes on 2 January 2026 "ended December 2025"
        when = "its latest fiscal year" if len(out) % 2 == 0 else f"the fiscal year ended {month} {f['fiscal_year']}"
        verb = "were" if item in ("assets", "current_liabilities", "cash") else "was"
        out.append(
            {
                "id": f"universe_{len(out) + 1:03d}",
                "question": f"What {verb} {f['name']}'s {ITEMS[item]} in {when}?",
                "answer": str(int(abs(value.value))),
                "tickers": [f["ticker"]],
            }
        )
    return out


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    out = Path(__file__).resolve().parent / "universe_set.yaml"
    header = "# Generated by eval/universe_set.py: lookups about companies outside the parsed filings, answers from XBRL.\n"
    qs = build()
    out.write_text(header + yaml.safe_dump({"questions": qs}, sort_keys=False, allow_unicode=True))
    log.info("%d questions", len(qs))


if __name__ == "__main__":
    main()
